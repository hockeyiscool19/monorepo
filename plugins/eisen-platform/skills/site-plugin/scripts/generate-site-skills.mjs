#!/usr/bin/env node
// Render one Claude skill per registered app from registry/registry.json. Zero dependencies; Node ≥ 18.
//
//   node plugins/eisen-platform/skills/site-plugin/scripts/generate-site-skills.mjs           write/refresh sites/site-<id>/SKILL.md
//   node plugins/eisen-platform/skills/site-plugin/scripts/generate-site-skills.mjs --check   exit 1 when any output is stale or missing
//   options: --registry <path> (default registry/registry.json) · --out <dir> (default ../sites) · --template <path>
//
// The template is templates/site-SKILL.md: `{{key}}` placeholders plus `{{#if key}}…{{/if}}` / `{{#unless key}}…{{/unless}}`
// blocks (nestable). An app with an `access` block gets an "Access" section: who may enter (group profiles by name from
// platform.auth.groups), whether the gateway door serves it, the door's session endpoint and refusals, and door-aware smoke
// tests. Output is deterministic — no timestamps — so the same registry always renders the same bytes and
// `--check` can compare byte for byte. A sites/<dir>/SKILL.md that carries the generated marker but whose id has left
// the registry is removed (or reported by --check). Hand-written files without the marker are never touched.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const skillDir = resolve(scriptDir, "..");
const repoRoot = resolve(skillDir, "..", "..", "..", "..");
const MARKER = "<!-- GENERATED by plugins/eisen-platform/skills/site-plugin/scripts/generate-site-skills.mjs";

function parseArgs(argv) {
  const opts = { check: false, registry: join(repoRoot, "registry", "registry.json"), out: resolve(skillDir, "..", "sites"), template: join(skillDir, "templates", "site-SKILL.md") };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--check") opts.check = true;
    else if (a === "--registry" || a === "--out" || a === "--template") opts[a.slice(2)] = resolve(argv[++i] ?? "");
    else if (a === "-h" || a === "--help") { console.log(readFileSync(fileURLToPath(import.meta.url), "utf8").split("\n").slice(1, 13).map((l) => l.replace(/^\/\/ ?/, "")).join("\n")); process.exit(0); }
    else throw new Error(`unknown option ${a}`);
  }
  return opts;
}

/** Expand {{#if k}}…{{/if}} and {{#unless k}}…{{/unless}} blocks (nested allowed), then {{k}} placeholders. */
export function render(template, ctx) {
  return renderBlocks(template, ctx).replace(/\{\{([A-Za-z0-9_]+)\}\}/g, (_m, key) => {
    if (!(key in ctx)) throw new Error(`template: unknown placeholder {{${key}}}`);
    return String(ctx[key]);
  });
}

/** End of a block tag match; a tag standing alone on its line also swallows that line's newline. */
function tagEnd(text, match) {
  const end = match.index + match[0].length;
  const standalone = (match.index === 0 || text[match.index - 1] === "\n") && text[end] === "\n";
  return standalone ? end + 1 : end;
}

function renderBlocks(tpl, ctx) {
  const openRe = /\{\{#(if|unless) ([A-Za-z0-9_]+)\}\}/;
  let out = "";
  let rest = tpl;
  for (;;) {
    const open = openRe.exec(rest);
    if (!open) return out + rest;
    out += rest.slice(0, open.index);
    const [, kind, key] = open;
    if (!(key in ctx)) throw new Error(`template: unknown block variable {{#${kind} ${key}}}`);
    const bodyStart = tagEnd(rest, open);
    const tagRe = /\{\{(#(?:if|unless) [A-Za-z0-9_]+|\/(?:if|unless))\}\}/g;
    tagRe.lastIndex = bodyStart;
    let depth = 1;
    let close = null;
    for (let t; (t = tagRe.exec(rest)); ) {
      depth += t[1].startsWith("#") ? 1 : -1;
      if (depth === 0) { close = t; break; }
    }
    if (!close) throw new Error(`template: unclosed {{#${kind} ${key}}}`);
    const inner = rest.slice(bodyStart, close.index);
    const truthy = Boolean(ctx[key]);
    if (kind === "if" ? truthy : !truthy) out += renderBlocks(inner, ctx);
    rest = rest.slice(tagEnd(rest, close));
  }
}

const AUTH_NOTES = {
  none: "No authentication: every endpoint answers anonymous requests.",
  cookie: "Browser-session auth: sign in through the browser first; with curl, reuse a saved cookie jar (`-b cookies.txt`). An unauthenticated call is redirected to sign-in or answered 401.",
  "firebase-id-token": "Send `Authorization: Bearer <Firebase ID token>`; obtain the token from the app's sign-in flow (the platform never holds one).",
  "api-key": "Send the key in the `X-API-Key` header; the app's README says where keys are issued.",
};

/** "👑 Jarl’s Court (`owner`), 🌿 Vale Circle (`vale`)" — group profiles by name, from platform.auth.groups. */
function groupNames(registry, ids) {
  const profiles = new Map((registry.platform.auth?.groups ?? []).map((g) => [g.id, g]));
  return ids.map((id) => {
    const g = profiles.get(id);
    return g ? `${g.emblem ? `${g.emblem} ` : ""}${g.name} (\`${id}\`)` : `\`${id}\``;
  }).join(", ");
}

/** The `access` part of the view model: who may enter and whether the gateway door is serving the app. */
function accessView(registry, app) {
  const access = app.access ?? null;
  const auth = registry.platform.auth ?? {};
  const gateway = registry.platform.gateway ?? {};
  const doorActive = Boolean(access) && auth.enabled === true && gateway.enabled === true;
  const groups = access?.groups ?? [];
  return {
    hasAccess: Boolean(access),
    accessWho: groups.length ? `signed-in members of ${groupNames(registry, groups)}` : "any signed-in person (no group needed)",
    accessNote: access?.note ?? "",
    doorActive,
    doorOffReason: auth.enabled !== true ? "`platform.auth.enabled` is false" : "`platform.gateway.enabled` is false",
    authProject: auth.projectId ?? "",
    sessionHours: String(auth.sessionHours ?? ""),
    gatewayService: gateway.service ?? "gateway",
  };
}

/** Everything the template can reference for one app. Strings only; booleans drive the blocks. */
export function viewModel(registry, app) {
  const domain = registry.platform.domain;
  const gateway = registry.platform.gateway ?? {};
  const ready = app.routing?.ready === true;
  const platformUrl = `https://${domain}${app.path}/`;
  const directUrl = app.web.url;
  const api = app.api ?? null;
  const d = app.deployment ?? {};
  const auth = api?.auth ?? "none";
  const access = accessView(registry, app);
  return {
    id: app.id, name: app.name, icon: app.icon ?? "", description: app.description, status: app.status, path: app.path,
    tags: (app.tags ?? []).map((t) => `\`${t}\``).join(", ") || "none",
    routingMode: app.routing?.mode ?? "path-prefix", routingReady: ready, routingNote: app.routing?.note ?? "",
    domain, platformUrl,
    platformUrlNote: !ready ? "not routable yet (`routing.ready` is false) — tiles link to the direct URL until the coordinator flips it"
      : access.doorActive ? "canonical URL, served through the gateway door (see Access); the full path is passed through"
      : "canonical URL; the Hosting rewrite passes the full path through",
    directUrl, directSmokeUrl: ready ? `${directUrl}${app.path}/` : `${directUrl}/`,
    altUrl: app.web.altUrl ?? "", service: app.web.service ?? "", region: app.web.region ?? "", project: app.web.project ?? "",
    hasApi: Boolean(api), apiBaseUrl: api?.baseUrl ?? "", healthPath: api?.healthPath ?? "", healthUrl: api ? `${api.baseUrl}${api.healthPath}` : "",
    auth, authNote: AUTH_NOTES[auth] ?? AUTH_NOTES.none, apiDocs: api?.docs ?? "",
    gatewayUrl: `https://${domain}${gateway.path ?? "/api"}/${app.id}/`, gatewayHealthUrl: `https://${domain}${gateway.path ?? "/api"}/health`,
    gatewayAppHealthUrl: api ? `https://${domain}${gateway.path ?? "/api"}/${app.id}${api.healthPath}` : "",
    gatewayEnabled: gateway.enabled === true,
    ...access,
    repoGithub: app.repo.github, repoUrl: `https://github.com/${app.repo.github}`, branch: app.repo.branch ?? "main", localPath: app.repo.localPath ?? "",
    version: d.version ?? "", sha: d.sha ?? "", imageTag: d.imageTag ?? "", deployedAt: d.deployedAt ?? "", deployedBy: d.deployedBy ?? "manual",
  };
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  const registry = JSON.parse(readFileSync(opts.registry, "utf8"));
  const template = readFileSync(opts.template, "utf8");
  if (!template.includes(MARKER)) throw new Error(`template ${opts.template} must contain the generated marker "${MARKER}"`);
  const apps = [...registry.apps].sort((a, b) => a.id.localeCompare(b.id));
  // Directory name = skill name (`site-<id>`), so the marketplace (which addresses skills by directory) and
  // install-host.sh (which links by frontmatter name) expose the same name, and it cannot collide with a host's own skill.
  const wanted = new Map(apps.map((app) => [`site-${app.id}`, render(template, viewModel(registry, app))]));

  const stale = [];
  let wrote = 0, unchanged = 0, removed = 0;
  for (const [dir, content] of wanted) {
    const file = join(opts.out, dir, "SKILL.md");
    const current = existsSync(file) ? readFileSync(file, "utf8") : null;
    if (current === content) { unchanged++; continue; }
    if (opts.check) { stale.push(`${relative(repoRoot, file)} (${current === null ? "missing" : "differs"})`); continue; }
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
    wrote++;
  }
  const existing = existsSync(opts.out) ? readdirSync(opts.out, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name) : [];
  for (const dir of existing) {
    if (wanted.has(dir)) continue;
    const file = join(opts.out, dir, "SKILL.md");
    if (!existsSync(file) || !readFileSync(file, "utf8").includes(MARKER)) continue;   // hand-written: leave it
    if (opts.check) { stale.push(`${relative(repoRoot, file)} (not generated from the current registry)`); continue; }
    rmSync(join(opts.out, dir), { recursive: true });
    removed++;
  }

  const where = relative(repoRoot, opts.out) || opts.out;
  if (opts.check) {
    if (stale.length) {
      console.error(`sites: ${stale.length} stale file(s):\n  - ${stale.join("\n  - ")}\nrun: node ${relative(repoRoot, fileURLToPath(import.meta.url))}`);
      process.exitCode = 1;   // not process.exit(): Node 24 on macOS can segfault inside it
      return;
    }
    console.log(`sites: up to date (${wanted.size} skill(s) in ${where})`);
    return;
  }
  console.log(`sites: ${wanted.size} skill(s) in ${where} — wrote ${wrote}, unchanged ${unchanged}, removed ${removed}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(); } catch (err) { console.error(`sites: ${err.message}`); process.exitCode = 2; }
}
